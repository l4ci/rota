package milestone

import (
	"path"
	"strings"

	"github.com/l4ci/rota/internal/fsio"
	"github.com/l4ci/rota/internal/rotatree"
	"github.com/l4ci/rota/internal/section"
)

// ItemsHeading names the generated section of a milestone detail file that
// lists the backlog items tagged with it.
const ItemsHeading = "Items"

const itemsNote = "<!-- generated by rota from the items' Milestone field; do not edit by hand -->"

// ItemRef is one backlog item as a milestone's Items section lists it.
type ItemRef struct {
	ID, Title string
	// Detail is the root-relative path of the item's detail file, "" when it has none.
	Detail string
	// Closed is the closure reason of a completed item ("done", "dropped", ...), "" while it is open.
	Closed string
}

var linkEscaper = strings.NewReplacer(`[`, `\[`, `]`, `\]`)

// itemsBody is the text of the Items section after its heading: the note and
// one bullet per item, linked to its detail file when it has one.
func itemsBody(items []ItemRef) string {
	var b strings.Builder
	b.WriteString("\n\n" + itemsNote + "\n\n")
	if len(items) == 0 {
		b.WriteString("_(no items)_\n")
	}
	for _, it := range items {
		text := "[" + it.ID + "] " + linkEscaper.Replace(it.Title)
		mark := ""
		if it.Closed != "" {
			mark = " (" + it.Closed + ")"
		}
		if it.Detail == "" {
			b.WriteString("- " + text + mark + "\n")
			continue
		}
		rel := path.Join("..", strings.TrimPrefix(it.Detail, rotatree.DirName+"/"))
		b.WriteString("- [" + text + "](" + rel + ")" + mark + "\n")
	}
	return b.String()
}

// SyncItems rewrites the Items section of milestone id's detail file from
// items, leaving the rest of the file alone. A milestone with no items and no
// section is not touched. changed is false when the section already matches.
func SyncItems(root, id string, items []ItemRef) (changed bool, err error) {
	return SyncItemsWith(root, id, func() ([]ItemRef, error) { return items, nil })
}

// SyncItemsWith is SyncItems with the items read by items. It runs inside the
// milestone file's lock, so the list it returns cannot go stale before the
// write; items may take other locks, and must take them after this one.
func SyncItemsWith(root, id string, items func() ([]ItemRef, error)) (changed bool, err error) {
	if err = checkID(id); err != nil {
		return
	}
	p := detailPath(root, id)
	err = fsio.Locked(p, fsio.LockTimeout, func() error {
		old, rerr := fsio.ReadText(p)
		if rerr != nil {
			return notFound(id)
		}
		list, ierr := items()
		if ierr != nil {
			return ierr
		}
		start, end, has := section.Find(old, ItemsHeading)
		if !has && len(list) == 0 {
			return nil
		}
		body := itemsBody(list)
		var next string
		if has {
			if end < len(old) {
				body += "\n"
			}
			next = strings.TrimRight(old[:start], " \t\r\n") + body + old[end:]
		} else {
			next = section.Replace(old, ItemsHeading, body[1:]) // Replace already ends a new heading with a newline
		}
		if next == old {
			return nil
		}
		changed = true
		return fsio.WriteFileAtomic(p, []byte(next))
	})
	return
}
