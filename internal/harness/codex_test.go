func TestCodexAgentInstructionsTOMLRoundTrip(t *testing.T) {
	for _, tc := range []struct{ name, instructions string }{
		{"option injection", "Report findings.\n\"\"\"\nmodel_provider = \"injected\"\ninjected_text = \"\"\"\nKeep reporting."},
		{"ordinary prose", "Read the code.\nReport \"findings\" with café and 日本語."},
		{"quote runs", "\" \"\" \"\"\" \"\"\"\" \"\"\"\"\" \"\"\"\"\"\"\"\""},
		{"literal escapes", "Keep \\n, \\t, \\u0041 and C:\\reports\\new literal.\\\n  Preserve indentation.\\"},
		{"control characters", "\x00\x01\x02\x03\x04\x05\x06\x07\b\t\n\x0b\f\r\x0e\x0f\x10\x11\x12\x13\x14\x15\x16\x17\x18\x19\x1a\x1b\x1c\x1d\x1e\x1f\x7f"},
		{"line endings", "\n\nKeep\r\nthese\rlines.\n"},
		{"empty", ""},
	} {
		t.Run(tc.name, func(t *testing.T) {
			assertCodexInstructionRoundTrip(t, tc.instructions)
		})
	}
}

func assertCodexInstructionRoundTrip(t *testing.T, instructions string) {
	t.Helper()
	files, err := (codex{}).AgentFiles(AgentRole{Name: "explorer", Description: "Explore", Instructions: instructions}, "")
	if err != nil {
		t.Fatal(err)
	}
	cmd := exec.Command("python3", "-c", "import json, sys, tomllib; json.dump(tomllib.loads(sys.stdin.read()), sys.stdout)")
	cmd.Stdin = strings.NewReader(files[0].Content)
	out, err := cmd.CombinedOutput()
	if err != nil {
		t.Fatalf("generated agent is invalid TOML: %v\n%s", err, out)
	}
	var parsed map[string]string
	if err := json.Unmarshal(out, &parsed); err != nil {
		t.Fatal(err)
	}
	if got := parsed["developer_instructions"]; got != instructions+"\n" {
		t.Errorf("instructions changed during TOML roundtrip: got %q, want %q", got, instructions+"\n")
	}
	if len(parsed) != 4 || parsed["sandbox_mode"] != "read-only" {
		t.Errorf("instructions changed agent options: %#v", parsed)
	}
}

